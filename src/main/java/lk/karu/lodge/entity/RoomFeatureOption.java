package lk.karu.lodge.entity;

import jakarta.persistence.*;


@Entity
@Table(name = "room_feature_options")
public class RoomFeatureOption {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    private int id;

    @Column(name = "name")
    private String name;

    public RoomFeatureOption() {
    }

    public RoomFeatureOption(String name) {
        this.name = name;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
